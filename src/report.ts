import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { createHash } from "node:crypto";
import { performance, monitorEventLoopDelay } from "node:perf_hooks";

/**
 * 本文件刻意构造两种典型的 Node.js 事件循环阻塞写法：
 *
 * 瓶颈 1 —— 同步 I/O：
 *   generatePage() 内部使用 fs.readFileSync 读取 ./config.json。
 *   readFileSync 在主线程（事件循环所在线程）上同步等待磁盘/系统调用，
 *   期间 libuv 事件循环被完全卡住，无法处理任何 I/O 回调、定时器或微任务之外的工作。
 *
 * 瓶颈 2 —— CPU 密集型串行计算：
 *   每个 <td> 单元格都调用 renderMetric(i)，其内部执行 MIX_ROUNDS 轮
 *   真实整数混合运算（Math.imul + 移位 + 三角函数），rowCount * columns
 *   个单元格在一个同步调用栈里串行算完。Node 主线程单线程执行 JS，
 *   这段纯 CPU 同步代码不释放线程，事件循环因此被长时间占住。
 */

export interface ReportConfig {
  title: string;
  generatedBy: string;
  columns: string[];
}

/** 每个 renderMetric 调用中 mixStep 的真实调用次数（>> 300 次函数执行）。 */
const MIX_ROUNDS = 80_000;

/** 单次混合步长：真实的整数运算，不是空转，也不返回常量。 */
function mixStep(state: number, salt: number): number {
  let next = Math.imul(state ^ salt, 0x27d4eb2d);
  next = Math.imul(next ^ (next >>> 15), 0x165667b1);
  if ((next & 7) === 0) {
    next ^= (Math.sin((next >>> 0) / (salt + 1)) * 1_000_000_000) | 0;
  }
  return next | 0;
}

function formatMetric(value: number): string {
  return value.toFixed(2);
}

function escapeHtml(input: string): string {
  return input
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");
}

function isReportConfig(value: unknown): value is ReportConfig {
  if (typeof value !== "object" || value === null) {
    return false;
  }
  const candidate = value as Record<string, unknown>;
  return (
    typeof candidate.title === "string" &&
    typeof candidate.generatedBy === "string" &&
    Array.isArray(candidate.columns) &&
    candidate.columns.every((column) => typeof column === "string")
  );
}

/**
 * 单元格指标渲染：纯 CPU、结果仅依赖 index，因此是确定性的。
 * 每次调用执行 MIX_ROUNDS 次 mixStep 函数调用（至少 8 万次函数执行），
 * 外加 Math.imul / Math.sin / toFixed 等真实运算。
 */
export function renderMetric(index: number): string {
  let accumulator = (0x811c9dc5 ^ index) | 0;
  let checksum = 0;
  for (let round = 0; round < MIX_ROUNDS; round++) {
    accumulator = mixStep(accumulator, index + round);
    checksum = (checksum + (accumulator >>> 0)) % 1_000_003;
  }
  const value = (checksum % 100_000) / 100;
  return formatMetric(value);
}

/**
 * 生成 HTML 报告。
 * 阻塞点：readFileSync 同步读配置 + rowCount * columns 次串行 CPU 计算。
 * 给定相同的 rowCount 和 config.json，输出逐字节一致。
 */
export function generatePage(rowCount: number): string {
  if (!Number.isInteger(rowCount) || rowCount < 0) {
    throw new Error("rowCount must be a non-negative integer");
  }

  // 阻塞点 1：同步文件 I/O，且内容参与最终拼接。
  const rawConfig = readFileSync(resolve("./config.json"), "utf8");
  const parsedConfig: unknown = JSON.parse(rawConfig);
  if (!isReportConfig(parsedConfig)) {
    throw new Error("config.json does not match ReportConfig shape");
  }
  const config: ReportConfig = parsedConfig;

  const headerCells = config.columns
    .map((column) => `<th>${escapeHtml(column)}</th>`)
    .join("");

  const rows: string[] = [];
  let cellIndex = 0;
  for (let row = 1; row <= rowCount; row++) {
    const cells: string[] = [`<th scope="row">${row}</th>`];
    for (let column = 0; column < config.columns.length; column++) {
      // 阻塞点 2：每个单元格都进行一次真实的 CPU 密集计算。
      cells.push(`<td data-column="${escapeHtml(config.columns[column])}">${renderMetric(cellIndex)}</td>`);
      cellIndex++;
    }
    rows.push(`<tr>${cells.join("")}</tr>`);
  }

  return [
    "<!doctype html>",
    `<html lang="en" data-generated-by="${escapeHtml(config.generatedBy)}">`,
    "<head>",
    '<meta charset="utf-8">',
    `<title>${escapeHtml(config.title)}</title>`,
    "</head>",
    "<body>",
    `<h1>${escapeHtml(config.title)}</h1>`,
    `<p>Rows: ${rowCount}, columns: ${config.columns.length}, config bytes: ${rawConfig.length}</p>`,
    "<table>",
    `<caption>${escapeHtml(config.title)}</caption>`,
    `<thead><tr><th scope="col">#</th>${headerCells}</tr></thead>`,
    `<tbody>${rows.join("")}</tbody>`,
    "</table>",
    `<footer>Generated by ${escapeHtml(config.generatedBy)}</footer>`,
    "</body>",
    "</html>",
    "",
  ].join("\n");
}

export interface BenchmarkResult {
  readonly rowCount: number;
  readonly cellCount: number;
  readonly runs: number;
  readonly firstRunMs: number;
  readonly totalMs: number;
  readonly averageMs: number;
  readonly minMs: number;
  readonly maxMs: number;
  /** perf_hooks monitorEventLoopDelay 记录的最大事件循环延迟（毫秒）。 */
  readonly eventLoopMaxDelayMs: number;
  /** 1ms 间隔定时器在阻塞期间观测到的最大被饿死延迟（毫秒）。 */
  readonly timerMaxLagMs: number;
  readonly consistent: boolean;
  readonly sha256: string;
  readonly outputBytes: number;
}

function hashContent(content: string): string {
  return createHash("sha256").update(content, "utf8").digest("hex");
}

/** 用 1ms setInterval 探针测量定时器被同步计算饿死后的最大延迟。 */
async function measureTimerLag(blockingWork: () => void): Promise<number> {
  let maxLag = 0;
  let lastTick = performance.now();
  const timer = setInterval(() => {
    const now = performance.now();
    const lag = now - lastTick - 1;
    if (lag > maxLag) {
      maxLag = lag;
    }
    lastTick = now;
  }, 1);

  // 先让探针在正常状态下 tick 几轮，建立时间基线。
  await new Promise((resolveTick) => setTimeout(resolveTick, 20));

  blockingWork();

  // 阻塞结束后让出事件循环，让被饿死的第一个 tick 得以执行并上报延迟。
  await new Promise((resolveTick) => setTimeout(resolveTick, 20));

  clearInterval(timer);
  return maxLag;
}

export async function benchmark(rowCount: number, runs = 3): Promise<BenchmarkResult> {
  if (!Number.isInteger(runs) || runs < 2) {
    throw new Error("runs must be an integer >= 2 for consistency checking");
  }

  const durationsMs: number[] = [];
  const hashes: string[] = [];
  let outputBytes = 0;

  const monitor = monitorEventLoopDelay();
  monitor.enable();

  // 让事件循环先正常迭代一轮，确保 monitor 有阻塞前基线。
  await new Promise((resolveTick) => setTimeout(resolveTick, 10));

  for (let run = 0; run < runs; run++) {
    const start = performance.now();
    const output = generatePage(rowCount);
    const end = performance.now();

    durationsMs.push(end - start);
    hashes.push(hashContent(output));
    if (run === 0) {
      outputBytes = Buffer.byteLength(output, "utf8");
    }

    // 让出事件循环：阻塞结束后的第一次迭代会把被卡住的时长计入 monitor。
    await new Promise((resolveTick) => setTimeout(resolveTick, 10));
  }

  monitor.disable();

  // 单独跑一次，期间用高频定时器观测事件循环被卡住的程度。
  const timerMaxLagMs = await measureTimerLag(() => {
    generatePage(rowCount);
  });

  const consistent = hashes.every((hash) => hash === hashes[0]);
  const totalMs = durationsMs.reduce((sum, value) => sum + value, 0);

  const columnCount = (JSON.parse(readFileSync(resolve("./config.json"), "utf8")) as ReportConfig).columns.length;

  return {
    rowCount,
    cellCount: rowCount * columnCount,
    runs,
    firstRunMs: durationsMs[0],
    totalMs,
    averageMs: totalMs / runs,
    minMs: Math.min(...durationsMs),
    maxMs: Math.max(...durationsMs),
    eventLoopMaxDelayMs: monitor.max / 1_000_000,
    timerMaxLagMs,
    consistent,
    sha256: hashes[0],
    outputBytes,
  };
}
